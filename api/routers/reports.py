from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from datetime import datetime, timedelta
import json

from database.connection import get_db
from database.models import Article, Report
from api.schemas import ReportRequest, ReportResponse
from services.crawler_service import CrawlerService

router = APIRouter(prefix="/reports")

@router.post("/generate", response_model=ReportResponse)
async def generate_report(request: ReportRequest, db: Session = Depends(get_db)):
    cutoff = datetime.utcnow() - timedelta(days=request.days_back)
    
    # Query matching articles
    articles = db.query(Article).filter(
        Article.news_type == request.news_type,
        Article.search_query.ilike(f"%{request.query}%"),
        Article.scraped_at >= cutoff
    ).order_by(Article.scraped_at.desc()).all()
    
    # If < 3 articles, trigger a fresh search
    if len(articles) < 3:
        crawler = CrawlerService(db)
        await crawler.run_search(request.query, request.news_type, num_results=10)
        # Re-query
        articles = db.query(Article).filter(
            Article.news_type == request.news_type,
            Article.search_query.ilike(f"%{request.query}%"),
            Article.scraped_at >= cutoff
        ).order_by(Article.scraped_at.desc()).all()
        
    if not articles:
        raise HTTPException(status_code=404, detail="Not enough articles found to generate report")
        
    # Build markdown report
    timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    
    markdown = f"# News Intelligence Report: {request.query}\n"
    markdown += f"**Generated:** {timestamp} | **Type:** {request.news_type} | **Articles Analysed:** {len(articles)}\n\n"
    markdown += "---\n\n"
    
    # Exec Summary - generated by concatenating top 3 summaries
    markdown += "## Executive Summary\n"
    exec_summary = " ".join([a.summary for a in articles[:3] if a.summary])
    if not exec_summary:
        exec_summary = "No sufficient summaries found for an executive overview."
    markdown += f"{exec_summary}\n\n---\n\n"
    
    markdown += "## Top Stories\n\n"
    for i, a in enumerate(articles[:8], 1):
        markdown += f"### {i}. {a.title}\n"
        date_str = a.published_at.strftime("%Y-%m-%d") if a.published_at else a.scraped_at.strftime("%Y-%m-%d")
        markdown += f"**Source:** {a.source} | **Published:** {date_str} | **Sentiment:** {a.sentiment_label} ({a.sentiment_score})\n\n"
        if a.summary:
            markdown += f"{a.summary}\n\n"
            
        if request.include_entities and a.entities_json:
            try:
                ents = json.loads(a.entities_json)
                top_ents = ents.get("persons", [])[:3] + ents.get("organizations", [])[:3]
                markdown += f"**Key Entities:** {', '.join(top_ents)}\n"
            except:
                pass
        markdown += f"**Read more:** {a.url}\n\n"
        
    markdown += "---\n\n"
    
    # Save Report
    report = Report(
        title=f"Intelligence Report: {request.query}",
        content_markdown=markdown,
        query=request.query,
        news_type=request.news_type,
        articles_count=len(articles),
        date_range_start=cutoff,
        date_range_end=datetime.utcnow()
    )
    db.add(report)
    db.commit()
    db.refresh(report)
    
    return report.to_dict()

@router.get("")
def list_reports(db: Session = Depends(get_db)):
    reports = db.query(Report).order_by(Report.generated_at.desc()).all()
    return [r.to_dict() for r in reports]

@router.get("/{id}", response_model=ReportResponse)
def get_report(id: int, db: Session = Depends(get_db)):
    report = db.query(Report).filter(Report.id == id).first()
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")
    return report.to_dict()
